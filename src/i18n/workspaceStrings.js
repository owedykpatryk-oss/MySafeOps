/** @type {Record<MarketId, Record<string, string>>} */
const DICTIONARIES = {
  uk: EN,
  au: EN,
  pl: PL,
  de: DE,
  at: DE,
  ch: DE,
};

/**
 * Translate a chrome string key for the given market. Falls back to English
 * for unknown keys/markets so a missed translation degrades gracefully
 * instead of rendering `undefined`.
 * @param {keyof typeof EN} key
 * @param {MarketId | string} [marketId]
 * @returns {string}
 */
export function t(key, marketId = "uk") {
  const dict = DICTIONARIES[marketId] || EN;
  return dict[key] ?? EN[key] ?? key;
}

/** Full dictionary for a market — use when destructuring many keys at once. */
export function getWorkspaceStrings(marketId = "uk") {
  return DICTIONARIES[marketId] || EN;
}

const DAY_KEY_MAP = {
  Mon: "dayMon", Tue: "dayTue", Wed: "dayWed", Thu: "dayThu", Fri: "dayFri", Sat: "daySat", Sun: "daySun",
};

/**
 * Display label for an internal English day-of-week key (Mon/Tue/…). The
 * underlying data model always keys timesheet days in English — only the
 * label shown to the user changes per market.
 * @param {"Mon"|"Tue"|"Wed"|"Thu"|"Fri"|"Sat"|"Sun"} dayKey
 * @param {MarketId | string} [marketId]
 */
export function dayLabel(dayKey, marketId = "uk") {
  const key = DAY_KEY_MAP[dayKey];
  return key ? t(key, marketId) : dayKey;
}

/**
 * Translate + interpolate `{placeholder}` tokens, e.g. tf("defaultMonthsValidity", "de", { n: 24 }).
 * @param {keyof typeof EN} key
 * @param {MarketId | string} marketId
 * @param {Record<string, string | number>} vars
 */
export function tf(key, marketId, vars = {}) {
  const template = t(key, marketId);
  return template.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}
